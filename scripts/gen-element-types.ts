/**
 * Generate types/a4-sheet.d.ts, the JSX types of <a4-sheet>, from the
 * attribute table in lib/element/contract.ts, so they can't drift from what
 * the element parses. With `--check`, fail when the file is stale instead of
 * writing it (run by `pnpm lint`).
 *
 *   pnpm gen:element-types
 */

// biome-ignore-all lint/suspicious/noTemplateCurlyInString: this script writes TypeScript template literal types such as `${number}` as text.

import { readFileSync, writeFileSync } from "node:fs";
import { assertNever } from "../lib/assert-never.ts";
import { ATTRIBUTES, type AttributeSpec } from "../lib/element/contract.ts";

const OUT = "types/a4-sheet.d.ts";

function literal(value: string): string {
  return JSON.stringify(value);
}

function tsType(spec: AttributeSpec): string {
  switch (spec.kind) {
    case "text":
      return "string";
    case "choice":
      return spec.values.map(literal).join(" | ");
    case "number":
      return "number | `${number}`";
    case "flag":
      return "boolean";
    case "lens":
      return [...spec.values.map(literal), "`model:${string}`"].join(" | ");
    case "zoom":
      return 'number | `${number}` | "fit"';
    default:
      return assertNever(spec);
  }
}

function property(spec: AttributeSpec): string {
  const name = /^[a-z]+$/.test(spec.name) ? spec.name : literal(spec.name);
  return `  /** ${spec.doc} */\n  ${name}?: ${tsType(spec)} | undefined;`;
}

const source = `// Generated by scripts/gen-element-types.ts from the attribute table in
// lib/element/contract.ts. Don't edit: change the table, then run
// \`pnpm gen:element-types\`.

import type { DetailedHTMLProps, HTMLAttributes, Ref } from "react";
import type { A4SheetElement } from "@/lib/element/a4-sheet";

/** The attributes of <a4-sheet>, as JSX props. */
interface A4SheetAttributes {
${Object.values(ATTRIBUTES).map(property).join("\n")}
}

declare module "react" {
  namespace JSX {
    interface IntrinsicElements {
      "a4-sheet": DetailedHTMLProps<HTMLAttributes<A4SheetElement>, A4SheetElement> &
        A4SheetAttributes & {
          ref?: Ref<A4SheetElement>;
          class?: string | undefined;
        };
    }
  }
}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    // Missing counts as stale.
  }
  if (current !== source) {
    console.error(`${OUT} is stale: run \`pnpm gen:element-types\` and commit the result.`);
    process.exitCode = 1;
  } else {
    console.log(`${OUT} matches the attribute table.`);
  }
} else {
  writeFileSync(OUT, source);
  console.log(`Wrote ${OUT}.`);
}
